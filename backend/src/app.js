import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import {pinoHttp} from 'pino-http';
import {randomUUID} from 'node:crypto';
import {ZodError} from 'zod';
import {env} from './config/env.js';
import {pool} from './database/pool.js';
import {AppError} from './lib/errors.js';
import {authRoutes} from './modules/auth/routes.js';
import {attendanceRoutes} from './modules/attendance/routes.js';
import {userRoutes} from './modules/users/routes.js';
export const app=express();
app.disable('x-powered-by');
if(env.TRUST_PROXY==='true')app.set('trust proxy',1);
app.use(pinoHttp({genReqId:()=>randomUUID(),redact:['req.headers.authorization','req.headers.cookie','res.headers["set-cookie"]'],autoLogging:env.NODE_ENV!=='test'}));
app.use(helmet());
app.use(cors({origin:env.CORS_ORIGINS.split(',').map(s=>s.trim())}));
app.use(express.json({limit:'16kb'}));
app.get('/health/live',(_req,res)=>res.json({status:'ok'}));
app.get('/health/ready',async(_req,res)=>{await pool.query('SELECT 1');res.json({status:'ok'});});
app.use('/api',(_req,res,next)=>{res.setHeader('Cache-Control','no-store');next();});
app.use('/api',rateLimit({windowMs:60000,limit:120,standardHeaders:'draft-7',legacyHeaders:false,message:{error:{code:'RATE_LIMIT',message:'Too many requests. Try again later'}}}));
app.use('/api/v1/auth',authRoutes);
app.use('/api/v1/attendance',attendanceRoutes);
app.use('/api/v1/users',userRoutes);
app.use((_req,_res,next)=>next(new AppError(404,'NOT_FOUND','Route not found')));
app.use((error,req,res,_next)=>{
 if(error instanceof ZodError)return res.status(400).json({error:{code:'VALIDATION_ERROR',message:'Check your input',details:error.flatten()}});
 if(error instanceof AppError)return res.status(error.status).json({error:{code:error.code,message:error.message}});
 if(error.code==='23505')return res.status(409).json({error:{code:'CONFLICT',message:'Email or attendance entry already exists; check for an open shift'}});
 if(error.type==='entity.parse.failed'||error.type==='entity.too.large')return res.status(error.type==='entity.too.large'?413:400).json({error:{code:'INVALID_BODY',message:'Request body is invalid or too large'}});
 req.log.error({err:error},'Request failed');
 res.status(500).json({error:{code:'INTERNAL_ERROR',message:'An unexpected error occurred',requestId:req.id}});
});
