import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {randomUUID} from 'node:crypto';

test('PostgreSQL workflow, role enforcement, concurrency and revocation',
 {skip:!process.env.TEST_DATABASE_URL},async()=>{
 const {default:pg}=await import('pg');
 const {default:request}=await import('supertest');
 const {default:bcrypt}=await import('bcryptjs');
 const schema='test_'+randomUUID().replaceAll('-','');
 const control=new pg.Pool({connectionString:process.env.TEST_DATABASE_URL});
 let pool;
 try{
  await control.query('CREATE SCHEMA '+schema);
  const url=new URL(process.env.TEST_DATABASE_URL);
  url.searchParams.set('options','-c search_path='+schema+',public');
  process.env.DATABASE_URL=url.toString();
  process.env.NODE_ENV='test';
  process.env.JWT_SECRET='integration-only-secret-with-32-characters';
  process.env.ATTENDANCE_FULL_MINUTES='480';
  process.env.ATTENDANCE_HALF_MINUTES='240';
  process.env.ATTENDANCE_WEEKLY_OFF='7';
  const {app}=await import('../src/app.js');
  ({pool}=await import('../src/database/pool.js'));
  await pool.query(await readFile(new URL('../migrations/001_initial.sql',import.meta.url),'utf8'));
  await pool.query(await readFile(new URL('../migrations/002_attendance_status.sql',import.meta.url),'utf8'));
  const hash=await bcrypt.hash('test-password-123',12);
  await pool.query("INSERT INTO users(name,email,password_hash,role) VALUES('Admin','admin@example.com',$1,'admin')",[hash]);
  const adminLogin=await request(app).post('/api/v1/auth/login').send({email:'admin@example.com',password:'test-password-123'}).expect(200);
  const admin='Bearer '+adminLogin.body.data.token;
  const employee=await request(app).post('/api/v1/users').set('Authorization',admin).send({name:'Employee',email:'employee@example.com',password:'test-password-123'}).expect(201);
  const login=await request(app).post('/api/v1/auth/login').send({email:'employee@example.com',password:'test-password-123'}).expect(200);
  const token='Bearer '+login.body.data.token;
  const employeeId=employee.body.data.id;
  await request(app).get('/api/v1/users').set('Authorization',token).expect(403);
  await request(app).get('/api/v1/attendance/report').set('Authorization',token).expect(403);
  await request(app).get('/api/v1/attendance/team-day').set('Authorization',token).expect(403);
  await request(app).get('/api/v1/attendance/calendar').query({userId:employeeId}).set('Authorization',token).expect(403);
  const team=await request(app).get('/api/v1/attendance/team-day').set('Authorization',admin).expect(200);
  assert.equal(team.body.data.length,2);
  assert.equal(team.body.data.find(row=>row.user_id===employeeId).check_in,null);
  const today=team.body.date;
  const pastDay='2025-11-17';
  await pool.query("UPDATE users SET created_at='2025-11-15T00:00:00Z' WHERE id=$1",[employeeId]);
  const past=await request(app).get('/api/v1/attendance/calendar').query({month:'2025-11'}).set('Authorization',token).expect(200);
  assert.equal(past.body.data.find(row=>row.work_date===pastDay).status,'absent');
  assert.equal(past.body.data.find(row=>row.work_date==='2025-11-16').status,'day_off');
  assert.ok(past.body.data.every(row=>row.user_id===employeeId && row.work_date>='2025-11-15'));
  const correction='/api/v1/attendance/correction/'+employeeId+'/'+pastDay;
  await request(app).put(correction).set('Authorization',token).send({status:'leave',reason:'Approved leave'}).expect(403);
  await request(app).put(correction).set('Authorization',admin).send({status:'leave',reason:'Approved leave'}).expect(204);
  const corrected=await request(app).get('/api/v1/attendance/calendar').query({month:'2025-11'}).set('Authorization',token).expect(200);
  const correctedDay=corrected.body.data.find(row=>row.work_date===pastDay);
  assert.equal(correctedDay.status,'leave');
  assert.equal(correctedDay.correction_reason,undefined);
  await request(app).put(correction).set('Authorization',admin).send({status:null,reason:'Removed override'}).expect(204);
  const {rows:changes}=await pool.query('SELECT status FROM attendance_correction_history ORDER BY id');
  assert.deepEqual(changes.map(row=>row.status),['leave',null]);
  const attempts=await Promise.all([1,2].map(()=>request(app).post('/api/v1/attendance/check-in').set('Authorization',token)));
  assert.deepEqual(attempts.map(r=>r.status).sort(),[201,409]);
  const open=await request(app).get('/api/v1/attendance/today').set('Authorization',token).expect(200);
  assert.equal(open.body.status,'checked_in');
  await request(app).post('/api/v1/attendance/check-out').set('Authorization',token).expect(200);
  await request(app).post('/api/v1/attendance/check-out').set('Authorization',token).expect(409);
  await pool.query("UPDATE attendance SET check_in=check_out-interval '4 hours' WHERE user_id=$1 AND work_date=$2",[employeeId,today]);
  const halfDay=await request(app).get('/api/v1/attendance/today').set('Authorization',token).expect(200);
  assert.equal(halfDay.body.status,'half_day');
  await pool.query("UPDATE attendance SET check_in=check_out-interval '8 hours' WHERE user_id=$1 AND work_date=$2",[employeeId,today]);
  const fullDay=await request(app).get('/api/v1/attendance/today').set('Authorization',token).expect(200);
  assert.equal(fullDay.body.status,'present');
  const history=await request(app).get('/api/v1/attendance/history').set('Authorization',token).expect(200);
  assert.equal(history.body.data.length,1);assert.ok(history.body.data[0].check_out);
  await pool.query("INSERT INTO attendance (user_id,work_date,check_in) VALUES ($1,$2,'2025-11-17T03:00:00Z')",[employeeId,pastDay]);
  const stale=await request(app).get('/api/v1/attendance/team-day').query({date:pastDay}).set('Authorization',admin).expect(200);
  assert.equal(stale.body.data.find(row=>row.user_id===employeeId).status,'missing_checkout');
  await request(app).put(correction).set('Authorization',admin)
    .send({status:null,reason:'Invalid time',checkOut:'2025-11-17T02:00:00Z'}).expect(409);
  await request(app).put(correction).set('Authorization',admin)
    .send({status:null,reason:'Confirmed departure',checkOut:'2025-11-17T11:00:00Z'}).expect(204);
  const repaired=await request(app).get('/api/v1/attendance/team-day').query({date:pastDay}).set('Authorization',admin).expect(200);
  assert.equal(repaired.body.data.find(row=>row.user_id===employeeId).status,'present');
  await request(app).patch('/api/v1/users/'+employee.body.data.id+'/status').set('Authorization',admin).send({active:false}).expect(200);
  await request(app).get('/api/v1/auth/me').set('Authorization',token).expect(401);
  await request(app).post('/api/v1/auth/logout').set('Authorization',admin).expect(204);
  await request(app).get('/api/v1/auth/me').set('Authorization',admin).expect(401);
 }finally{
  if(pool)await pool.end();
  await control.query('DROP SCHEMA IF EXISTS '+schema+' CASCADE');
  await control.end();
 }
});
